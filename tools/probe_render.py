#!/usr/bin/env python3
"""Probe-render: verify N moments of a HyperFrames composition in ONE short render.

Why this exists
---------------
The browser preview pane cannot verify these compositions. Pages are served as
`data:` URLs, so relative assets break; a local http.server is sandboxed off
/Volumes; and self-contained base64 pages hit the tab cap and get their data
URIs stripped. Every one of those was tried and failed on horizons-thanks.

More importantly, the preview is the WRONG oracle even when it works: it cannot
show you how a graphic sits against real footage luma, and it does not exercise
the actual render path (font embedding, gradient clipping, filter support).

So instead of previewing, we RENDER — but only the frames we care about. This
builds a throwaway copy of the composition whose timeline is an outer wrapper
that hand-seeks the real timeline to a list of checkpoints, holding each for
`step` seconds. Ten checkpoints render in ~13 seconds instead of ~6 minutes,
using the same renderer that produces the deliverable.

Frame `i*fps*step + 3` of the output is checkpoint `i`.

Usage
-----
    probe_render.py COMP_DIR OUT_DIR --checkpoints 1.2,3.0,4.0 \
        [--base VIDEO --base-offset 0.0] [--alpha] [--step 0.2] [--fps 30]

`--base` composites each probe frame over the real footage at the matching
timestamp, which is the whole point for alpha overlays: it is the only way to
see contrast failures before burning a full render + composite cycle.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

NODE_BIN = "/opt/homebrew/opt/node@22/bin"
HF = ["npx", "--yes", "hyperframes@0.6.6"]

# Replaces the composition's own two-line registration. `tl` is already built
# and paused at this point in the source file, so we simply never register it
# and register an outer timeline that scrubs it instead.
# NOTE: plain string + .replace(), NOT .format() — this is JavaScript, it is
# full of braces, and every one of them would have to be doubled.
OUTER = """
  /* ---- probe harness (generated by tools/probe_render.py) ---- */
  window.__timelines = window.__timelines || {};
  const __CK = [@CKS@], __STEP = @STEP@;
  const __outer = gsap.timeline({ paused: true });
  const __proxy = { i: 0 };
  __outer.to(__proxy, {
    i: __CK.length, duration: __CK.length * __STEP, ease: "none",
    onUpdate: () => tl.time(__CK[Math.min(__CK.length - 1, Math.floor(__proxy.i))])
  }, 0);
  __outer.to({}, { duration: __CK.length * __STEP }, 0);
  window.__timelines["main"] = __outer;
"""


def build_probe(comp_dir: Path, probe_dir: Path, checkpoints: list[float], step: float) -> None:
    # rm -rf, not shutil.rmtree: this repo lives on an exFAT volume that
    # materialises AppleDouble "._" sidecars, and rmtree dies on them mid-walk
    # with FileNotFoundError.
    subprocess.run(["rm", "-rf", str(probe_dir)], check=True)
    probe_dir.mkdir(parents=True)

    # copy everything except renders/ and nested probes — assets must travel or
    # <img src="logo.png"> resolves to nothing and the panel renders empty.
    for item in comp_dir.iterdir():
        if item.name.startswith((".", "_")) or item.name in {"renders", "probe_proj"}:
            continue
        (shutil.copytree if item.is_dir() else shutil.copy2)(item, probe_dir / item.name)

    html = (comp_dir / "index.html").read_text()

    total = len(checkpoints) * step
    html, n = re.subn(r'data-duration="[^"]*"', f'data-duration="{total}"', html, count=1)
    if not n:
        sys.exit("no data-duration on the composition root")

    # strip the real registration, whatever whitespace it uses
    html, n = re.subn(
        r'\n\s*window\.__timelines\s*=\s*window\.__timelines\s*\|\|\s*\{\}\s*;'
        r'\s*\n\s*window\.__timelines\[[^\]]+\]\s*=\s*tl\s*;',
        lambda _m: "\n" + (OUTER
                           .replace("@CKS@", ", ".join(str(c) for c in checkpoints))
                           .replace("@STEP@", str(step))),
        html, count=1)
    if not n:
        sys.exit("could not find the `window.__timelines[...] = tl;` registration to replace")

    (probe_dir / "index.html").write_text(html)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("comp_dir", type=Path)
    ap.add_argument("out_dir", type=Path)
    ap.add_argument("--checkpoints", required=True, help="comma-separated composition times")
    ap.add_argument("--step", type=float, default=0.2)
    ap.add_argument("--fps", type=int, default=30)
    ap.add_argument("--alpha", action="store_true", help="render ProRes 4444 mov instead of mp4")
    ap.add_argument("--base", type=Path, help="footage to composite each checkpoint over")
    ap.add_argument("--base-offset", type=float, default=0.0,
                    help="base_time = checkpoint + offset")
    args = ap.parse_args()

    cks = [float(x) for x in args.checkpoints.split(",")]
    comp_dir = args.comp_dir.resolve()
    out_dir = args.out_dir.resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    probe_dir = comp_dir / "probe_proj"

    build_probe(comp_dir, probe_dir, cks, args.step)

    env = dict(os.environ, PATH=f"{NODE_BIN}:{os.environ['PATH']}")
    fmt = ["--format", "mov"] if args.alpha else []
    out = probe_dir / ("probe.mov" if args.alpha else "probe.mp4")
    r = subprocess.run(HF + ["render", *fmt, "--fps", str(args.fps), "--output", str(out)],
                       cwd=probe_dir, env=env, capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout[-3000:]); print(r.stderr[-3000:])
        return 1

    hold = int(args.fps * args.step)
    for i, ck in enumerate(cks):
        frame = i * hold + 3          # mid-hold, safely clear of both edges
        dst = out_dir / f"ck_{ck:.2f}.png"
        if args.base:
            # overlay the probe frame on the footage frame it will actually sit on
            subprocess.run([
                "ffmpeg", "-y", "-v", "error",
                "-ss", str(ck + args.base_offset), "-i", str(args.base),
                "-i", str(out),
                "-filter_complex",
                f"[1:v]select='eq(n\\,{frame})',setpts=N/({args.fps}*TB)[o];"
                f"[0:v]setsar=1[b];[b][o]overlay=0:0:format=auto[v]",
                "-map", "[v]", "-frames:v", "1", str(dst)], check=True)
        else:
            subprocess.run([
                "ffmpeg", "-y", "-v", "error", "-i", str(out),
                "-vf", f"select='eq(n\\,{frame})'", "-vsync", "0",
                "-frames:v", "1", str(dst)], check=True)
        print(f"  ck {ck:6.2f}s -> {dst.name}")

    subprocess.run(["rm", "-rf", str(probe_dir)], check=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
